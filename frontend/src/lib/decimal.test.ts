import { describe, expect, it } from 'vitest'
import { subDecimal } from './decimal'

describe('subDecimal', () => {
  it.each([
    ['10.50', '3.25', '7.25'],
    ['0.1', '0.3', '-0.2'],
    ['100', '100', '0'],
    ['-5', '2.5', '-7.5'],
    ['0.000000000000000002', '0.000000000000000001', '0.000000000000000001'],
    ['1234567890123.123456789', '0.000000001', '1234567890123.123456788'],
    ['', '1', '-1'],
  ])('%s - %s = %s', (a, b, want) => {
    expect(subDecimal(a, b)).toBe(want)
  })
})
